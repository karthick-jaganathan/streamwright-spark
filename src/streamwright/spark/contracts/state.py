"""The bookkeeping store protocol (runtime.state). PROPOSED. Implementations: state.store.SqlStateStore (sqlite, postgres)."""

from typing import Any, List, Mapping, Optional, Protocol, Sequence, runtime_checkable

from streamwright.spark.contracts.types import Lease, WriteReceipt


__all__ = ["StateStore"]


@runtime_checkable
class StateStore(Protocol):
    def init(self) -> None: ...
    def acquire_lease(self, job: str, owner: str, ttl_seconds: int) -> Lease: ...
    def renew_lease(self, lease: Lease, ttl_seconds: int) -> Lease: ...
    def release_lease(self, lease: Lease) -> None: ...
    def next_seq(self, job: str) -> int: ...
    def batch_by_run_key(self, job: str, run_key: str) -> Optional[Mapping[str, Any]]: ...
    def record_batch(self, lease: Lease, batch_id: str, status: str, manifest: Mapping[str, Any], seq: Optional[int] = None,
                     run_key: Optional[str] = None, error: Optional[str] = None,
                     app_id: Optional[str] = None, driver_host: Optional[str] = None) -> None:
        """Rejects writes from a stale epoch (fencing) and impossible status changes."""
    def record_receipt(self, lease: Lease, batch_id: str, receipt: WriteReceipt) -> None: ...
    def receipts(self, job: str, batch_id: str) -> Mapping[str, Any]: ...
    def outbox_add(self, lease: Lease, batch_id: str, topic: str, rows: Sequence[Mapping[str, Any]], output: str = "") -> None: ...
    def outbox_pending(self, job: str) -> List[Mapping[str, Any]]: ...
    def outbox_mark_sent(self, lease: Lease, batch_id: str, output: str, seqs: Sequence[int]) -> None: ...
    def batch(self, job: str, batch_id: str) -> Optional[Mapping[str, Any]]: ...
    def incomplete(self, job: str) -> List[Mapping[str, Any]]: ...
    def list_batches(self, job: str, limit: int = 20) -> List[Mapping[str, Any]]: ...
    def purge(self, job: str, older_than_iso: str) -> int: ...
